/** Expand query terms with glossary translations. Kannada keys match as substrings to tolerate inflection. */
export function expandTerms(text: string): string[] {
  const lower = text.toLowerCase();
  const terms = new Set<string>();
  for (const [kannada, english] of Object.entries(KANNADA_GLOSSARY)) {
    if (lower.includes(kannada)) english.forEach((term) => terms.add(term));
  }
  for (const [word, synonyms] of Object.entries(ENGLISH_SYNONYMS)) {
    if (new RegExp(`\\b${word}\\b`).test(lower)) synonyms.forEach((term) => terms.add(term));
  }
  return [...terms];
}
