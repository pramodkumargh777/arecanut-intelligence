/** Language detection, Kannada digit normalisation and bilingual UI strings for the ANI assistant. */
export type Language = "en" | "kn";

const KANNADA = /[\u0C80-\u0CFF]/;
const KANNADA_DIGITS = "೦೧೨೩೪೫೬೭೮೯";

export function detectLanguage(text: string, requested?: Language | "auto"): Language {
  if (requested === "en" || requested === "kn") return requested;
  return KANNADA.test(text) ? "kn" : "en";
}

/** Replace Kannada numerals with ASCII digits so numeric extraction and grounding work on both scripts. */
export function normalizeDigits(text: string): string {
  return text.replace(/[೦-೯]/g, (digit) => String(KANNADA_DIGITS.indexOf(digit)));
}

